import assert from 'node:assert/strict';
import test from 'node:test';
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

test('workerd D1 enforces featured limit inside Rust transactions', async () => {
  const env={...process.env,PATH:'/opt/homebrew/bin:'+process.env.PATH};
  const wrangler=execFileSync('which',['wrangler'],{env,encoding:'utf8'}).trim();
  const require=createRequire(realpathSync(wrangler));
  const {Miniflare}=await import(pathToFileURL(require.resolve('miniflare')).href);
  const dir=mkdtempSync(join(tmpdir(),'bpmedia-featured-worker-'));
  let mf;
  try {
    copyFileSync('server-rust/build/index.js',join(dir,'index.js'));
    copyFileSync('server-rust/build/index_bg.wasm',join(dir,'index_bg.wasm'));
    writeFileSync(join(dir,'test-wrapper.js'),"import Rust from './index.js'; export default { fetch(request,env,ctx) { return new Rust(ctx,env).fetch(request); } };\n");
    mf=new Miniflare({modulesRoot:dir,modules:[{type:'ESModule',path:join(dir,'test-wrapper.js')},{type:'ESModule',path:join(dir,'index.js')},{type:'CompiledWasm',path:join(dir,'index_bg.wasm')}],compatibilityDate:'2024-09-23',d1Databases:{DB:'synthetic-featured-limit'}});
    const db=await mf.getD1Database('DB');
    const schema=readFileSync('db/schema.sql','utf8');
    await db.prepare(schema.match(/CREATE TABLE IF NOT EXISTS posts \([\s\S]*?\);/)[0]).run();
    await db.prepare('ALTER TABLE posts ADD COLUMN author_user_id INTEGER').run();
    await db.prepare(schema.match(/CREATE TABLE IF NOT EXISTS post_history \([\s\S]*?\);/)[0]).run();
    await db.prepare("INSERT INTO posts(id,category,title,featured,published) VALUES(1,'korea','A',1,1),(2,'korea','B',1,1),(3,'korea','C',1,1),(4,'korea','D',1,1),(5,'korea','Candidate',0,1)").run();
    const send=(path,body)=>mf.dispatchFetch('https://synthetic.invalid/__internal/'+path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
    const bindings=['korea','blocked','', 'body',null,null,null,null,null,null,null,null,null,null,null,'Editor.A',null,0,1,1,null];
    const created=await send('post-create',{bindings});
    assert.equal(created.status,200);
    assert.equal((await created.json()).featuredLimit,true);
    assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM posts').first()).n,5);
    const existing=await send('post-update',{id:1,fields:['featured = ?', 'title = ?',"updated_at = datetime('now')"],values:[1,'Edited'],action:'status',summary:'synthetic',expectedUpdatedAt:null,featuredGuard:true,claim:'post-history:existing'});
    assert.equal(existing.status,200);
    assert.equal((await existing.json()).changes,1);
    assert.equal((await db.prepare('SELECT title FROM posts WHERE id=1').first()).title,'Edited');
    const edited=await send('post-update',{id:5,fields:['featured = ?',"updated_at = datetime('now')"],values:[1],action:'status',summary:'synthetic',expectedUpdatedAt:null,featuredGuard:true,claim:'post-history:synthetic'});
    assert.equal(edited.status,200);
    assert.equal((await edited.json()).featuredLimit,true);
    assert.equal((await db.prepare('SELECT featured FROM posts WHERE id=5').first()).featured,0);
    assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM post_history WHERE post_id=5').first()).n,0);
    await db.prepare('UPDATE posts SET featured=0 WHERE id=4').run();
    const accepted=await send('post-update',{id:5,fields:['featured = ?',"updated_at = datetime('now')"],values:[1],action:'status',summary:'synthetic',expectedUpdatedAt:null,featuredGuard:true,claim:'post-history:accepted'});
    assert.equal(accepted.status,200);
    assert.equal((await accepted.json()).changes,1);
    assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM post_history WHERE post_id=5').first()).n,1);
    await db.prepare('CREATE TABLE settings(key TEXT PRIMARY KEY,value TEXT)').run();
    await db.prepare("INSERT INTO settings(key,value) VALUES('tags','original')").run();
    await db.prepare("UPDATE posts SET tag='Camp, education' WHERE id=1").run();
    const tagAttempt=await send('tag-commit',{value:'changed',expected:'original',removed:['Camp']});
    assert.equal(tagAttempt.status,200);
    assert.equal((await tagAttempt.json()).changes,0);
    assert.equal((await db.prepare("SELECT value FROM settings WHERE key='tags'").first()).value,'original');
    await db.prepare('UPDATE posts SET tag=NULL WHERE id=1').run();
    const tagAccepted=await send('tag-commit',{value:'changed',expected:'original',removed:['Camp']});
    assert.equal((await tagAccepted.json()).changes,1);
    const stale=await send('tag-commit',{value:'stale',expected:'original',removed:[]});
    assert.equal((await stale.json()).changes,0);
    assert.equal((await db.prepare("SELECT value FROM settings WHERE key='tags'").first()).value,'changed');
    await db.prepare("DELETE FROM settings WHERE key='tags'").run();
    await db.prepare("UPDATE posts SET tag='Camp' WHERE id=1").run();
    const missingSetting=await send('tag-commit',{value:'new',expected:null,removed:['Camp']});
    assert.equal((await missingSetting.json()).changes,0);
    assert.equal(await db.prepare("SELECT value FROM settings WHERE key='tags'").first(),null);
    await db.prepare('CREATE TABLE calendar_events(id INTEGER PRIMARY KEY,title TEXT NOT NULL,start_at TEXT NOT NULL)').run();
    await db.prepare("INSERT INTO calendar_events(id,title,start_at) VALUES(1,'보존 일정','2027-01-01')").run();
    assert.equal((await send('calendar-ensure',{})).status,200);
    assert.equal((await send('calendar-ensure',{})).status,200);
    const calendarColumns=(await db.prepare('PRAGMA table_info(calendar_events)').all()).results.map(row=>row.name);
    assert(calendarColumns.includes('target_groups'));
    assert(calendarColumns.includes('related_posts_json'));
    const oldEvent=await db.prepare('SELECT title,event_category FROM calendar_events WHERE id=1').first();
    assert.equal(oldEvent.title,'보존 일정');
    assert.equal(oldEvent.event_category,'WOSM');
    await db.prepare('CREATE TABLE site_visits(id INTEGER PRIMARY KEY,viewer_key TEXT,path TEXT)').run();
    await db.prepare("INSERT INTO site_visits VALUES(1,'viewer','/article')").run();
    assert.equal((await send('site-visit-ensure',{})).status,200);
    assert.equal((await send('site-visit-ensure',{})).status,200);
    const visitColumns=(await db.prepare('PRAGMA table_info(site_visits)').all()).results.map(row=>row.name);
    assert(visitColumns.includes('country_code') && visitColumns.includes('longitude'));
    assert.equal((await db.prepare('SELECT path FROM site_visits WHERE id=1').first()).path,'/article');
    assert(await db.prepare("SELECT name FROM sqlite_master WHERE type='index' AND name='idx_site_visits_country_code'").first());
    await db.prepare('CREATE TABLE homepage_issues(id INTEGER PRIMARY KEY,title TEXT NOT NULL,status TEXT,severity TEXT,updated_at TEXT)').run();
    await db.prepare("INSERT INTO homepage_issues VALUES(1,'기존 장애','open','high','2026-01-01')").run();
    assert.equal((await send('homepage-issue-ensure',{})).status,200);
    assert.equal((await send('homepage-issue-ensure',{})).status,200);
    const issueColumns=(await db.prepare('PRAGMA table_info(homepage_issues)').all()).results.map(row=>row.name);
    assert(issueColumns.includes('last_seen_at') && issueColumns.includes('occurrence_count'));
    const oldIssue=await db.prepare('SELECT title,occurrence_count FROM homepage_issues WHERE id=1').first();
    assert.equal(oldIssue.title,'기존 장애');
    assert.equal(oldIssue.occurrence_count,1);
    assert(await db.prepare("SELECT name FROM sqlite_master WHERE type='index' AND name='idx_homepage_issues_status_updated'").first());
    assert.equal((await send('rate-ensure',{})).status,200);
    const rates=await Promise.all(Array.from({length:8},()=>send('rate-enforce',{key:'synthetic:user',now:1700000100,limit:3,window:60}).then(r=>r.json())));
    assert.equal(rates.filter(result=>result.ok).length,3);
    assert.equal(rates.filter(result=>!result.ok).length,5);
    assert(rates.filter(result=>!result.ok).every(result=>result.retryAfter===60));
    assert.equal((await db.prepare("SELECT count FROM api_rate_limit WHERE bucket_key='synthetic:user'").first()).count,3);
    await db.prepare("UPDATE api_rate_limit SET window_start_at=1700000040 WHERE bucket_key='synthetic:user'").run();
    const reset=await (await send('rate-enforce',{key:'synthetic:user',now:1700000100,limit:3,window:60})).json();
    assert.deepEqual(reset,{ok:true,remaining:2,windowSeconds:60});
    await db.prepare('ALTER TABLE site_visits ADD COLUMN visited_at TEXT').run();
    await db.prepare("INSERT INTO site_visits(id,viewer_key,path,visited_at) VALUES(2,'v2','/post/1','2026-10-20 00:00:00')").run();
    await db.prepare('CREATE TABLE post_likes(post_id INTEGER,liked_at TEXT)').run();
    await db.prepare("INSERT INTO post_likes VALUES(1,'2026-10-20 00:00:00')").run();
    await db.prepare("UPDATE posts SET image_url='https://example.invalid/photo.jpg',publish_at='2026-10-20 12:00:00',content='합성 본문' WHERE id=1").run();
    await db.prepare('CREATE TABLE card_news(id INTEGER PRIMARY KEY,title TEXT,slug TEXT UNIQUE,r2_key TEXT,size_bytes INTEGER,published INTEGER,data TEXT)').run();
    const weeklyQuery={operation:'candidates',utcStart:'2026-10-18 15:00:00',utcEnd:'2026-10-25 14:00:00',start:'2026-10-19 00:00:00',end:'2026-10-25 23:00:00',publicDateExpr:'COALESCE(publish_at, created_at)'};
    const candidates=await (await send('card-news-weekly',weeklyQuery)).json();
    assert.deepEqual(candidates.results.map(row=>row.id),[1]);
    assert.equal(candidates.results[0].attention_score,4);
    assert.equal((await (await send('card-news-weekly',{operation:'find',slug:'weekly-synthetic'})).json()).row,null);
    const draft=JSON.stringify({title:'합성 주간',articles:[{id:1}],auto_publish:false});
    const weeklyWrites=await Promise.all(['첫 제목','둘째 제목'].map(title=>send('card-news-weekly',{operation:'insert',title,slug:'weekly-synthetic',size:draft.length,data:draft}).then(response=>response.json())));
    assert.equal(weeklyWrites[0].row.id,weeklyWrites[1].row.id);
    const weeklyStored=await db.prepare("SELECT published,data,size_bytes FROM card_news WHERE slug='weekly-synthetic'").first();
    assert.equal(weeklyStored.published,0);
    assert.equal(weeklyStored.data,draft);
    assert.equal(weeklyStored.size_bytes,draft.length);
    assert.equal((await db.prepare("SELECT COUNT(*) AS n FROM card_news WHERE slug='weekly-synthetic'").first()).n,1);
  } finally {if(mf) await mf.dispose();rmSync(dir,{recursive:true,force:true});}
});
