import assert from 'node:assert/strict';
import test from 'node:test';
import {execFileSync} from 'node:child_process';
import {mkdtempSync,readdirSync,readFileSync,realpathSync,rmSync,writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {join,resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {pathToFileURL} from 'node:url';
import {createToken} from '../functions/_shared/auth.js';

test('isolated workerd validates uploads before writing to synthetic R2',async()=>{
  const env={...process.env,PATH:'/opt/homebrew/bin:'+process.env.PATH,CI:'1',WRANGLER_SEND_METRICS:'false'};
  const wrangler=execFileSync('which',['wrangler'],{env,encoding:'utf8'}).trim();
  const require=createRequire(realpathSync(wrangler));
  const {Miniflare}=await import(pathToFileURL(require.resolve('miniflare')).href);
  const dir=mkdtempSync(join(tmpdir(),'bpmedia-upload-test-'));
  let mf;
  try {
    execFileSync(wrangler,['pages','functions','build','functions','--outdir',dir],{env,stdio:'pipe'});
    const files=readdirSync(dir).sort((a,b)=>Number(b.endsWith('.js'))-Number(a.endsWith('.js')));
    const bundlePath=resolve(dir,files.find(name=>name.endsWith('.js'))),bundle=readFileSync(bundlePath,'utf8');
    const injection='async function queryRust(context, route, options) {';
    assert.equal(bundle.split(injection).length,2);
    writeFileSync(bundlePath,bundle.replace(injection,injection+"\n  if (route === 'image-storage-key') { await context.env.TEST_SSR_FAULT.put('image-storage-key-hit','1'); if (await context.env.TEST_SSR_FAULT.get('image-storage-key') === '1') return new Response('synthetic fault', {status:503}); }\n  if (route === 'image-mime') { await context.env.TEST_SSR_FAULT.put('image-mime-hit','1'); if (await context.env.TEST_SSR_FAULT.get('image-mime') === '1') return new Response('synthetic fault', {status:503}); }\n  if (route === 'image-magic' && await context.env.TEST_SSR_FAULT.get('image-magic') === '1') return new Response('synthetic fault', {status:503});"));
    const secret='synthetic-upload-test-only';
    mf=new Miniflare({modulesRoot:dir,modules:files.map(name=>({type:name.endsWith('.wasm')?'CompiledWasm':'ESModule',path:resolve(dir,name)})),compatibilityDate:'2024-09-23',d1Databases:{DB:'synthetic-upload-test'},r2Buckets:{POST_IMAGES:'synthetic-upload-test'},kvNamespaces:{TEST_SSR_FAULT:'synthetic-upload-fault'},bindings:{ADMIN_SECRET:secret},serviceBindings:{ASSETS:()=>new Response('',{status:404})},outboundService:()=>new Response('',{status:503})});
    const token=await createToken(secret,{role:'full'});
    const headers={Cookie:'admin_token='+token,Origin:'https://synthetic.invalid','Content-Type':'application/json'};
    const send=(data,auth=true)=>mf.dispatchFetch('https://synthetic.invalid/api/memorabilia/upload-image',{method:'POST',headers:auth?headers:{Origin:'https://synthetic.invalid','Content-Type':'application/json'},body:JSON.stringify({data_url:data})});
    const bucket=await mf.getR2Bucket('POST_IMAGES');
    assert.equal((await send('data:image/png;base64,AAAA',false)).status,401);
    const svg=await send('data:image/svg+xml;base64,PHN2Zy8+');
    assert.equal(svg.status,415);assert.equal((await svg.json()).error,'unsupported_type');
    const oversized=await send('data:image/png;base64,'+'x'.repeat(12*1024*1024));
    assert.equal(oversized.status,413);
    assert.equal((await bucket.list()).objects.length,0);
    const png='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a7WQAAAAASUVORK5CYII=';
    const mismatch=await send('data:image/jpeg;base64,'+png);
    assert.equal(mismatch.status,500);
    assert.equal((await bucket.list()).objects.length,0);
    const success=await send('data:image/png;base64,'+png);
    assert.equal(success.status,200);
    const result=await success.json();
    assert.match(result.key,/^memorabilia-[a-f0-9-]+\.png$/);
    const object=await bucket.get(result.key);
    assert(object);assert.equal(object.httpMetadata.contentType,'image/png');
    assert.deepEqual(Buffer.from(await object.arrayBuffer()),Buffer.from(png,'base64'));
    const served=await mf.dispatchFetch('https://synthetic.invalid/api/images/'+encodeURIComponent(result.key));
    assert.equal(served.status,200);assert.equal(served.headers.get('content-type'),'image/png');
    for(const [mime,bytes,extension] of [['image/jpeg',Buffer.from([255,216,255,0,0,0,0,0,0,0,0,0]),'jpg'],['image/gif',Buffer.from('GIF89a123456'),'gif'],['image/webp',Buffer.from('RIFF1234WEBP'),'webp']]) {
      const response=await send(`data:${mime};base64,${bytes.toString('base64')}`);
      assert.equal(response.status,200);
      const uploaded=await response.json();
      assert(uploaded.key.endsWith('.'+extension));
      const stored=await bucket.get(uploaded.key);
      assert.equal(stored.httpMetadata.contentType,mime);
      assert.deepEqual(Buffer.from(await stored.arrayBuffer()),bytes);
    }
    const fault=await mf.getKVNamespace('TEST_SSR_FAULT');
    assert.equal(await fault.get('image-mime-hit'),'1');
    await fault.put('image-mime','1');
    const fallbackMime=await send('data:image/png;base64,'+png);
    assert.equal(fallbackMime.status,200);
    await fault.delete('image-mime');
    await fault.put('image-magic','1');
    const fallbackUpload=await send('data:image/png;base64,'+png);
    assert.equal(fallbackUpload.status,200);
    const fallbackMismatch=await send('data:image/jpeg;base64,'+png);
    assert.equal(fallbackMismatch.status,500);
    await fault.delete('image-magic');
    const db=await mf.getD1Database('DB');
    await db.prepare('CREATE TABLE settings(key TEXT PRIMARY KEY,value TEXT)').run();
    const oldKey='합성 이전 이미지.png',keepKey='합성 보존 이미지.png';
    await bucket.put(oldKey,'old'); await bucket.put(keepKey,'keep');
    const oldUrl='https://synthetic.invalid/api/images/'+encodeURIComponent(oldKey);
    await db.prepare("INSERT INTO settings(key,value) VALUES('site_meta',?)").bind(JSON.stringify({image_url:oldUrl})).run();
    const replace=await mf.dispatchFetch('https://synthetic.invalid/api/settings/site-meta',{method:'PUT',headers,body:JSON.stringify({image_url:'https://synthetic.invalid/new.png',if_revision:0})});
    assert.equal(replace.status,200,await replace.clone().text());
    assert.equal(await fault.get('image-storage-key-hit'),'1');
    assert.equal(await bucket.get(oldKey),null);
    assert(await bucket.get(keepKey));
    const fallbackKey='합성 대체 경로.png';
    await bucket.put(fallbackKey,'old');
    await db.prepare("UPDATE settings SET value=? WHERE key='site_meta'").bind(JSON.stringify({image_url:'https://synthetic.invalid/api/images/'+encodeURIComponent(fallbackKey)})).run();
    await fault.put('image-storage-key','1');
    const replaceFallback=await mf.dispatchFetch('https://synthetic.invalid/api/settings/site-meta',{method:'PUT',headers,body:JSON.stringify({image_url:'https://synthetic.invalid/next.png',if_revision:1})});
    assert.equal(replaceFallback.status,200,await replaceFallback.clone().text());
    assert.equal(await bucket.get(fallbackKey),null);
    assert(await bucket.get(keepKey));
  } finally {if(mf)await mf.dispose();rmSync(dir,{recursive:true,force:true});}
});
